#!/usr/bin/env python3
"""Writes bench/plan.txt, the list of measured runs read by bench/run_measure.bat.

One line per run: phase;config;arm;mode;tag;options. Empty fields are written as '-' because
the batch parser collapses consecutive separators. Runs are ordered so that the shortest
datasets come first inside each phase, and the phases so that the main comparison comes first.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'bench', 'plan.txt')

DATASETS = ['sign', 'leviathan', 'fifa', 'bible', 'bms1', 'D45K', 'D48K', 'kosarak']
MAIN_ARMS = ['IncAdaTaSPM', 'IncAdaTaSPM-NoBuffer', 'IncAdaTaSPM-StaticPreLarge', 'IncAdaTaSPM-Original',
             'RemineTaSPM', 'BatchTaSPM', 'ItemPreLargeTaSPM']
ETAS = ['0', '0.1', '0.3', '0.5', '0.7', '0.9']
LAMBDAS = ['0.1', '0.3', '0.5', '0.7', '0.9']
MAIN_ETA, MAIN_LAMBDA = '0.5', '0.1'

rows = []
def add(phase, ds, arm, mode, tag='-', opts='--reps=auto'):
    rows.append(';'.join([phase, 'stream_%s.txt' % ds, arm, mode, tag, opts]))

for ds in DATASETS:
    for arm in MAIN_ARMS:
        add('main-time', ds, arm, 'time')
for ds in DATASETS:
    for arm in MAIN_ARMS:
        add('main-live', ds, arm, 'live')
for ds in DATASETS:
    add('tbr', ds, 'IncAdaTaSPM-TBR', 'time')
    add('tbr', ds, 'IncAdaTaSPM-TBR', 'live')
for ds in DATASETS:
    for phi in ['0.25', '1']:
        add('phi', ds, 'IncAdaTaSPM', 'time', 'phi%s' % phi, '--reps=auto --phi=%s' % phi)
for ds in ['bms1', 'D48K']:
    for eta in ETAS:
        for lam in LAMBDAS:
            if (eta, lam) == (MAIN_ETA, MAIN_LAMBDA):
                continue
            add('eta-lambda', ds, 'IncAdaTaSPM', 'time', 'eta%s_lambda%s' % (eta, lam), '--reps=auto --eta=%s --lambda=%s' % (eta, lam))
for ds in DATASETS:
    for k in ['25', '50', '67']:
        for arm in ['IncAdaTaSPM', 'RemineTaSPM']:
            add('batch-count', ds, arm, 'time', 'K%s' % k, '--reps=auto --batch_count=%s' % k)
for pct in ['20', '40', '60', '80']:
    for arm in ['IncAdaTaSPM', 'RemineTaSPM']:
        add('kosarak-scale', 'kosarak_%s' % pct, arm, 'time')
        add('kosarak-scale', 'kosarak_%s' % pct, arm, 'live')

with open(OUT, 'w', newline='\n') as f:
    f.write('# phase;config;arm;mode;tag;options  (generated by tools/gen_measure_plan.py; do not edit by hand)\n')
    for r in rows:
        f.write(r + '\n')
phases = {}
for r in rows:
    phases[r.split(';')[0]] = phases.get(r.split(';')[0], 0) + 1
print(len(rows), 'runs:', ', '.join('%s %d' % kv for kv in phases.items()))
