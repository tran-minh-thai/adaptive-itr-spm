#!/usr/bin/env python3
"""Writes bench/plan.txt, the list of measured runs read by bench/run_measure.bat.

One line per run: phase;config;arm;mode;tag;options. Empty fields are written as '-' because
the batch parser collapses consecutive separators. Runs are ordered so that the shortest
datasets come first inside each phase, and the phases so that the main comparison comes first.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'bench', 'plan.txt')

# D45K (synthetic) is not part of the experiments (author's decision, 2026-11-12); its data
# file and configuration stay in the repository.
DATASETS = ['sign', 'leviathan', 'fifa', 'bible', 'bms1', 'D48K', 'kosarak']
MAIN_ARMS = ['IncAdaTaSPM', 'IncAdaTaSPM-NoBuffer', 'IncAdaTaSPM-StaticPreLarge', 'IncAdaTaSPM-Original',
             'RemineTaSPM', 'BatchTaSPM', 'ItemPreLargeTaSPM']
ETAS = ['0', '0.1', '0.3', '0.5', '0.7', '0.9']
LAMBDAS = ['0.1', '0.3', '0.5', '0.7', '0.9']
MAIN_ETA, MAIN_LAMBDA = '0.5', '0.1'

rows = []
def add(phase, ds, arm, mode, tag='-', opts='--reps=auto'):
    rows.append(';'.join([phase, 'stream_%s.txt' % ds, arm, mode, tag, opts]))

for ds in DATASETS:
    for arm in MAIN_ARMS:
        add('main-time', ds, arm, 'time')
for ds in DATASETS:
    for arm in MAIN_ARMS:
        add('main-live', ds, arm, 'live')
for ds in DATASETS:
    add('tbr', ds, 'IncAdaTaSPM-TBR', 'time')
    add('tbr', ds, 'IncAdaTaSPM-TBR', 'live')
for ds in DATASETS:
    for phi in ['0.25', '1']:
        add('phi', ds, 'IncAdaTaSPM', 'time', 'phi%s' % phi, '--reps=auto --phi=%s' % phi)
for ds in ['bms1', 'D48K']:
    for eta in ETAS:
        for lam in LAMBDAS:
            if (eta, lam) == (MAIN_ETA, MAIN_LAMBDA):
                continue
            add('eta-lambda', ds, 'IncAdaTaSPM', 'time', 'eta%s_lambda%s' % (eta, lam), '--reps=auto --eta=%s --lambda=%s' % (eta, lam))
for ds in DATASETS:
    for k in ['25', '50', '67']:
        for arm in ['IncAdaTaSPM', 'RemineTaSPM']:
            add('batch-count', ds, arm, 'time', 'K%s' % k, '--reps=auto --batch_count=%s' % k)
for pct in ['20', '40', '60', '80']:
    for arm in ['IncAdaTaSPM', 'RemineTaSPM']:
        add('kosarak-scale', 'kosarak_%s' % pct, arm, 'time')
        add('kosarak-scale', 'kosarak_%s' % pct, arm, 'live')

# Supplementary phases (2026-11-15). Decision D4 makes IncAdaTaSPM-StaticPreLarge (fixed pre-large
# threshold LB = (1 - eta) min_sup, exact-count stubs, lazy insertion) the proposed method; the
# sweeps above ran on IncAdaTaSPM (Score-based threshold). These lines repeat the sweeps on the
# proposed arm. W_TBR and lambda act only through Score, which is 1 for this arm, so neither is
# swept. The recheck lines repeat runs of the main campaign unchanged, to measure the drift
# between the two sessions before results of the two sessions are compared.
PROPOSED = 'IncAdaTaSPM-StaticPreLarge'
for ds in DATASETS:
    add('sup-recheck', ds, PROPOSED, 'time', 'recheck')
for ds in ['bms1', 'D48K']:
    add('sup-recheck', ds, 'RemineTaSPM', 'time', 'recheck')
add('sup-recheck', 'kosarak_20', 'RemineTaSPM', 'time', 'recheck')
for ds in DATASETS:
    for phi in ['0.25', '1']:
        add('sup-phi', ds, PROPOSED, 'time', 'phi%s' % phi, '--reps=auto --phi=%s' % phi)
for ds in DATASETS:
    for eta in ETAS:
        if eta == MAIN_ETA:
            continue
        add('sup-eta', ds, PROPOSED, 'time', 'eta%s' % eta, '--reps=auto --eta=%s' % eta)
for ds in DATASETS:
    for k in ['25', '50', '67']:
        add('sup-batch-count', ds, PROPOSED, 'time', 'K%s' % k, '--reps=auto --batch_count=%s' % k)
for pct in ['20', '40', '60', '80']:
    add('sup-kosarak-scale', 'kosarak_%s' % pct, PROPOSED, 'time')
    add('sup-kosarak-scale', 'kosarak_%s' % pct, PROPOSED, 'live')

# Batch baseline after the projection fix (2026-11-16, docs/stream-benchmark.md section 6). Only the
# BatchTaSPM classes changed; the proposed method is measured again in the same session so that the
# ratios involving Batch do not mix two sessions. Shortest Batch runs first; FIFA (time limit) last.
for ds in ['bms1', 'D48K', 'bible', 'sign', 'leviathan', 'kosarak', 'fifa']:
    add('fix-batch', ds, PROPOSED, 'time', 'recheck3')
    add('fix-batch', ds, 'BatchTaSPM', 'time', 'fullproj')
    add('fix-batch', ds, 'BatchTaSPM', 'live', 'fullproj')
    add('fix-batch', ds, PROPOSED, 'live', 'recheck3')

with open(OUT, 'w', newline='\n') as f:
    f.write('# phase;config;arm;mode;tag;options  (generated by tools/gen_measure_plan.py; do not edit by hand)\n')
    for r in rows:
        f.write(r + '\n')
phases = {}
for r in rows:
    phases[r.split(';')[0]] = phases.get(r.split(';')[0], 0) + 1
print(len(rows), 'runs:', ', '.join('%s %d' % kv for kv in phases.items()))
